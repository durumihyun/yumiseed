// ===== Render Reviews =====
const reviewsGrid = document.getElementById('reviewsGrid');
const loadMoreBtn = document.getElementById('loadMoreReviews');
let visibleCount = 6;
const increment = 6;

function renderReviews(count) {
    const reviewsToShow = allReviews.slice(0, count);
    reviewsGrid.innerHTML = reviewsToShow.map(review => `
    <div class="review-card">
      <div class="review-stars">★★★★★</div>
      <div class="review-id">${review.id}</div>
      <div class="review-text">${review.text}</div>
    </div>
  `).join('');

    // Hide button if all reviews are shown
    if (count >= allReviews.length) {
        loadMoreBtn.style.display = 'none';
    } else {
        loadMoreBtn.style.display = 'inline-block';
    }
}

// Initial render
renderReviews(visibleCount);

// Load more
loadMoreBtn.addEventListener('click', () => {
    visibleCount += increment;
    renderReviews(visibleCount);
});

// ===== Mobile Menu Toggle =====
const menuToggle = document.getElementById('menuToggle');
const menuClose = document.getElementById('menuClose');
const mobileMenu = document.getElementById('mobileMenu');

menuToggle.addEventListener('click', () => {
    mobileMenu.classList.add('active');
    document.body.style.overflow = 'hidden';
});

menuClose.addEventListener('click', () => {
    mobileMenu.classList.remove('active');
    document.body.style.overflow = '';
});

// Close mobile menu when clicking a link
document.querySelectorAll('.mobile-nav-menu a').forEach(link => {
    link.addEventListener('click', () => {
        mobileMenu.classList.remove('active');
        document.body.style.overflow = '';
    });
});
